def build_pdf(path: Path, title: str, sections) -> None:
    pdfmetrics.registerFont(TTFont("DejaVu", str(FONTS / "DejaVuSans.ttf")))
    pdfmetrics.registerFont(TTFont("DejaVu-Bold", str(FONTS / "DejaVuSans-Bold.ttf")))
    h0 = ParagraphStyle("h0", fontName="DejaVu-Bold", fontSize=17, leading=22, spaceAfter=6 * mm)
    h1 = ParagraphStyle("h1", fontName="DejaVu-Bold", fontSize=13, leading=17, spaceBefore=6 * mm, spaceAfter=3 * mm)
    body = ParagraphStyle("body", fontName="DejaVu", fontSize=10.5, leading=15, spaceAfter=2.5 * mm)
    doc = SimpleDocTemplate(
        str(path), pagesize=A4, title=title, author=COMPANY,
        leftMargin=22 * mm, rightMargin=20 * mm, topMargin=20 * mm, bottomMargin=20 * mm,
    )
    story = [Paragraph(title, h0), Paragraph(COMPANY, body), Spacer(1, 3 * mm)]
    for heading, points in sections:
        story.append(Paragraph(heading, h1))
        for p in points:
            story.append(Paragraph(p.replace("&", "&amp;").replace("<", "&lt;"), body))
    doc.build(story)


def build_docx(path: Path) -> None:
    doc = Document()
    doc.add_heading(KOM_TITLE, level=0)
    doc.add_paragraph(COMPANY)
    for heading, points in KOM:
        doc.add_heading(heading, level=1)
        for p in points:
            doc.add_paragraph(p)
        if heading.startswith("3."):
            doc.add_heading("Таблица 1. Суточные и лимиты проживания по городам", level=2)
            table = doc.add_table(rows=1, cols=len(KOM_TABLE_HEADER))
            table.style = "Table Grid"
            for cell, text in zip(table.rows[0].cells, KOM_TABLE_HEADER):
                cell.text = text
                for r in cell.paragraphs[0].runs:
                    r.bold = True
            for row in KOM_TABLE:
                cells = table.add_row().cells
                for cell, text in zip(cells, row):
                    cell.text = text
            doc.add_paragraph("")
    doc.save(str(path))


def build_md(path: Path) -> None:
    lines = [f"# {RW_TITLE}", "", COMPANY, ""]
    for heading, points in RW:
        lines += [f"## {heading}", ""]
        for p in points:
            lines += [p, ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def build_txt(path: Path) -> None:
    blocks = [f"Вопрос: {q}\nОтвет: {a}" for q, a in FAQ]
    path.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")


def pdf_page_of(path: Path, marker: str) -> int:
    norm = lambda s: re.sub(r"\s+", " ", s)
    for i, page in enumerate(PdfReader(str(path)).pages, 1):
        if norm(marker) in norm(page.extract_text() or ""):
            return i
    raise RuntimeError(f"маркер не найден в {path.name}: {marker}")


def build_facts(path: Path) -> None:
    lines = [
        "# Факты для проверки ответов бота",
        "",
        f"Вымышленная компания: {COMPANY}. Файл создаётся скриптом scripts/generate_docs.py и не загружается в индекс.",
        "",
        "| № | Вопрос | Ожидаемый ответ | Файл | Страница / раздел |",
        "|---|--------|-----------------|------|-------------------|",
    ]
    for n, (q, a, f, section, marker) in enumerate(FACTS, 1):
        if f.endswith(".pdf"):
            loc = f'стр. {pdf_page_of(OUT / f, marker)}, раздел "{section}"'
        else:
            loc = section
        lines.append(f"| {n} | {q} | {a} | {f} | {loc} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


